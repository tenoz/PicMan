/** 扩展名 → 图标 + 颜色 */
const TYPE_MAP: Record<string, { icon: keyof typeof ICONS; color: string }> = {
  jpg: { icon: 'file-jpg', color: 'text-sky-500' },
  jpeg: { icon: 'file-jpg', color: 'text-sky-500' },
  png: { icon: 'file-png', color: 'text-emerald-500' },
  gif: { icon: 'file-gif', color: 'text-amber-500' },
  webp: { icon: 'file-image', color: 'text-violet-500' },
  bmp: { icon: 'file-image', color: 'text-violet-500' },
};

const extOf = (name: string): string => {
  const i = name.lastIndexOf('.');
  return i === -1 ? '' : name.slice(i + 1).toLowerCase();
};

export const ImageTypeBadge: React.FC<{ name: string; onClick?: () => void; size?: number }> = ({
  name,
  onClick,
  size = 20,
}) => {
  const mapped = TYPE_MAP[extOf(name)];
  const icon = ICONS[mapped?.icon ?? 'file'];
  const color = mapped?.color ?? 'text-gray-400 dark:text-gray-500';

  return (
    <button
      type="button"
      onClick={onClick}
      title={`${extOf(name).toUpperCase() || '文件'} · 点击预览原图`}
      className="flex-shrink-0 w-9 h-9 rounded-md flex items-center justify-center cursor-pointer hover:bg-gray-100 dark:hover:bg-gray-700/60 transition-colors"
    >
      <svg
        viewBox={icon.viewBox}
        width={size}
        height={size}
        fill="currentColor"
        className={color}
        aria-hidden="true"
      >
        <path d={icon.d} />
      </svg>
    </button>
  );
};

export default ImageTypeBadge;
